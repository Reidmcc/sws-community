// sws_check.exe (issue #17): does this copy of STAR WARS: Squadrons match the build the mod is made for?
//
// For players with the game from the EA app or the Epic Games Store (or anywhere): it only READS the game's exe (mapped
// read-only), never starts or changes anything, and writes sws_check_report.txt beside itself, never in the game folder.
//   sws_check.exe                      finds the game (Windows' uninstall entries, Epic's manifests, Steam's libraries)
//   sws_check.exe <path to starwarssquadrons.exe>      or drag the exe onto sws_check.exe
// It compares the whole file's SHA-256 with the Steam build's (same hash: the same build), and the bytes at every game
// address the mod uses (check_sites.h, generated by tools/gen_check_sites.py; stored as hashes, not game bytes).
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <bcrypt.h>
#include <stdio.h>
#include <stdint.h>
#include <string>
#include <vector>
#include "check_sites.h"
#pragma comment(lib, "bcrypt.lib")
#pragma comment(lib, "advapi32.lib")
#pragma comment(lib, "version.lib")

static FILE* g_report;
static void out(const char* fmt, ...) {
    char buf[2048]; va_list ap; va_start(ap, fmt); vsnprintf(buf, sizeof buf, fmt, ap); va_end(ap);
    fputs(buf, stdout); if (g_report) fputs(buf, g_report);
}
static std::string narrow(const std::wstring& w) {
    int n = WideCharToMultiByte(CP_UTF8, 0, w.c_str(), -1, nullptr, 0, nullptr, nullptr);
    std::string s(n > 0 ? n - 1 : 0, '\0'); if (n > 1) WideCharToMultiByte(CP_UTF8, 0, w.c_str(), -1, &s[0], n, nullptr, nullptr);
    return s;
}
static bool exists(const std::wstring& p) { DWORD a = GetFileAttributesW(p.c_str()); return a != INVALID_FILE_ATTRIBUTES && !(a & FILE_ATTRIBUTE_DIRECTORY); }

struct Candidate { std::wstring path, source; };
static void add(std::vector<Candidate>& c, std::wstring dir, const wchar_t* source) {
    while (!dir.empty() && (dir.back() == L'\\' || dir.back() == L'/' || dir.back() == L'"')) dir.pop_back();
    if (!dir.empty() && dir[0] == L'"') dir.erase(0, 1);
    std::wstring exe = dir + L"\\starwarssquadrons.exe";
    if (!exists(exe)) return;
    for (auto& x : c) if (!_wcsicmp(x.path.c_str(), exe.c_str())) return;
    c.push_back({ exe, source });
}
// installed programs whose name mentions Squadrons (the EA app and Steam write these)
static void from_uninstall(std::vector<Candidate>& c, HKEY root, REGSAM view) {
    HKEY k; if (RegOpenKeyExW(root, L"Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall", 0, KEY_READ | view, &k)) return;
    wchar_t name[256];
    for (DWORD i = 0;; i++) {
        DWORD n = 256;
        if (RegEnumKeyExW(k, i, name, &n, nullptr, nullptr, nullptr, nullptr) != ERROR_SUCCESS) break;
        HKEY s; if (RegOpenKeyExW(k, name, 0, KEY_READ | view, &s)) continue;
        wchar_t disp[512] = L"", loc[MAX_PATH] = L"", pub[256] = L""; DWORD sz;
        sz = sizeof disp; RegGetValueW(s, nullptr, L"DisplayName", RRF_RT_REG_SZ, nullptr, disp, &sz);
        sz = sizeof loc; RegGetValueW(s, nullptr, L"InstallLocation", RRF_RT_REG_SZ, nullptr, loc, &sz);
        sz = sizeof pub; RegGetValueW(s, nullptr, L"Publisher", RRF_RT_REG_SZ, nullptr, pub, &sz);
        _wcslwr_s(disp);
        if (wcsstr(disp, L"squadrons") && loc[0]) {
            const wchar_t* src = wcsstr(name, L"Steam App") ? L"Steam" : L"installed programs (EA app or other)";
            add(c, loc, src);
        }
        RegCloseKey(s);
    }
    RegCloseKey(k);
}
// the Epic Games launcher's install manifests: one JSON file per game, with "InstallLocation"
static void from_epic(std::vector<Candidate>& c) {
    WIN32_FIND_DATAW fd; HANDLE h = FindFirstFileW(L"C:\\ProgramData\\Epic\\EpicGamesLauncher\\Data\\Manifests\\*.item", &fd);
    if (h == INVALID_HANDLE_VALUE) return;
    do {
        std::wstring p = std::wstring(L"C:\\ProgramData\\Epic\\EpicGamesLauncher\\Data\\Manifests\\") + fd.cFileName;
        FILE* f = nullptr; if (_wfopen_s(&f, p.c_str(), L"rb") || !f) continue;
        std::string j; char buf[4096]; size_t n; while ((n = fread(buf, 1, sizeof buf, f)) > 0) j.append(buf, n); fclose(f);
        std::string low = j; for (auto& ch : low) ch = (char)tolower((unsigned char)ch);
        if (low.find("squadrons") == std::string::npos) continue;
        size_t at = j.find("\"InstallLocation\""); if (at == std::string::npos) continue;
        size_t q1 = j.find('"', j.find(':', at) + 1), q2 = q1 == std::string::npos ? q1 : j.find('"', q1 + 1);
        if (q1 == std::string::npos || q2 == std::string::npos) continue;
        std::string loc = j.substr(q1 + 1, q2 - q1 - 1); std::string fixed;
        for (size_t i = 0; i < loc.size(); i++) { if (loc[i] == '\\' && i + 1 < loc.size() && loc[i + 1] == '\\') i++; fixed += loc[i]; }
        int wn = MultiByteToWideChar(CP_UTF8, 0, fixed.c_str(), -1, nullptr, 0); std::wstring w(wn > 0 ? wn - 1 : 0, L'\0');
        if (wn > 1) MultiByteToWideChar(CP_UTF8, 0, fixed.c_str(), -1, &w[0], wn);
        add(c, w, L"Epic Games Store");
    } while (FindNextFileW(h, &fd));
    FindClose(h);
}
// Steam's library folders (as the launcher finds the game)
static void from_steam(std::vector<Candidate>& c) {
    wchar_t steam[MAX_PATH] = L""; DWORD sz = sizeof steam;
    if (RegGetValueW(HKEY_CURRENT_USER, L"Software\\Valve\\Steam", L"SteamPath", RRF_RT_REG_SZ, nullptr, steam, &sz)) return;
    for (wchar_t* p = steam; *p; p++) if (*p == L'/') *p = L'\\';
    std::vector<std::wstring> libs{ steam };
    FILE* f = nullptr; std::wstring vdf = std::wstring(steam) + L"\\steamapps\\libraryfolders.vdf";
    if (!_wfopen_s(&f, vdf.c_str(), L"rb") && f) {
        char line[1024];
        while (fgets(line, sizeof line, f)) {
            char* k = strstr(line, "\"path\""); if (!k) continue;
            char* a = strchr(k + 6, '"'); char* b = a ? strchr(a + 1, '"') : nullptr; if (!a || !b) continue;
            std::string p(a + 1, b); std::string fixed; for (size_t i = 0; i < p.size(); i++) { if (p[i] == '\\' && i + 1 < p.size() && p[i + 1] == '\\') i++; fixed += p[i]; }
            int wn = MultiByteToWideChar(CP_UTF8, 0, fixed.c_str(), -1, nullptr, 0); std::wstring w(wn > 0 ? wn - 1 : 0, L'\0');
            if (wn > 1) MultiByteToWideChar(CP_UTF8, 0, fixed.c_str(), -1, &w[0], wn);
            libs.push_back(w);
        }
        fclose(f);
    }
    for (auto& l : libs) add(c, l + L"\\steamapps\\common\\STAR WARS Squadrons", L"Steam");
}

static bool sha256(const uint8_t* data, size_t n, char hex[65]) {
    BCRYPT_ALG_HANDLE alg; BCRYPT_HASH_HANDLE h; uint8_t d[32];
    if (BCryptOpenAlgorithmProvider(&alg, BCRYPT_SHA256_ALGORITHM, nullptr, 0)) return false;
    bool ok = !BCryptCreateHash(alg, &h, nullptr, 0, nullptr, 0, 0);
    for (size_t off = 0; ok && off < n; off += (1u << 30)) ok = !BCryptHashData(h, (PUCHAR)data + off, (ULONG)min((size_t)1 << 30, n - off), 0);
    ok = ok && !BCryptFinishHash(h, d, 32, 0);
    BCryptDestroyHash(h); BCryptCloseAlgorithmProvider(alg, 0);
    for (int i = 0; ok && i < 32; i++) sprintf_s(hex + 2 * i, 3, "%02x", d[i]);
    return ok;
}
static uint32_t fnv1a(const uint8_t* b, size_t n) { uint32_t h = 2166136261u; for (size_t i = 0; i < n; i++) { h ^= b[i]; h *= 16777619u; } return h; }

// check one exe; returns 0 same build, 1 compatible (every address matches), 2 differs, 3 couldn't read
static int check(const std::wstring& path, const std::wstring& source) {
    out("Game: %s\nFound through: %s\n", narrow(path).c_str(), narrow(source).c_str());
    {   // the exe's own version stamp, if it has one
        DWORD z = 0, sz = GetFileVersionInfoSizeW(path.c_str(), &z);
        std::vector<uint8_t> vi(sz ? sz : 1); VS_FIXEDFILEINFO* ffi = nullptr; UINT fl = 0;
        if (sz && GetFileVersionInfoW(path.c_str(), 0, sz, vi.data()) && VerQueryValueW(vi.data(), L"\\", (void**)&ffi, &fl) && ffi)
            out("File version: %u.%u.%u.%u\n", HIWORD(ffi->dwFileVersionMS), LOWORD(ffi->dwFileVersionMS), HIWORD(ffi->dwFileVersionLS), LOWORD(ffi->dwFileVersionLS));
    }
    HANDLE f = CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr, OPEN_EXISTING, 0, nullptr);
    if (f == INVALID_HANDLE_VALUE) { out("Could not open it for reading (error %lu).\n\n", GetLastError()); return 3; }
    LARGE_INTEGER size; GetFileSizeEx(f, &size);
    HANDLE m = CreateFileMappingW(f, nullptr, PAGE_READONLY, 0, 0, nullptr);
    const uint8_t* base = m ? (const uint8_t*)MapViewOfFile(m, FILE_MAP_READ, 0, 0, 0) : nullptr;
    if (!base) { out("Could not map it for reading (error %lu).\n\n", GetLastError()); if (m) CloseHandle(m); CloseHandle(f); return 3; }
    size_t n = (size_t)size.QuadPart;
    out("Size: %llu bytes (the Steam build: %llu)\n", (unsigned long long)n, kSteamSize);
    char hex[65] = "";
    sha256(base, n, hex);
    bool same = !strcmp(hex, kSteamSha256);
    out("SHA-256: %s\n  Steam: %s\n", hex, kSteamSha256);
    int result = 0;
    if (same) out("=> The SAME BUILD as the Steam copy the mod is made for.\n");
    // the bytes at each address the mod uses, through the exe's own section table
    const IMAGE_DOS_HEADER* dos = (const IMAGE_DOS_HEADER*)base;
    const IMAGE_NT_HEADERS64* nt = n > sizeof *dos && dos->e_magic == IMAGE_DOS_SIGNATURE && (size_t)dos->e_lfanew + sizeof(IMAGE_NT_HEADERS64) < n
        ? (const IMAGE_NT_HEADERS64*)(base + dos->e_lfanew) : nullptr;
    if (!nt || nt->Signature != IMAGE_NT_SIGNATURE || nt->OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR64_MAGIC) {
        out("Not a 64-bit Windows program?\n\n"); UnmapViewOfFile(base); CloseHandle(m); CloseHandle(f); return 3;
    }
    uint64_t imageBase = nt->OptionalHeader.ImageBase;
    const IMAGE_SECTION_HEADER* sec = IMAGE_FIRST_SECTION(nt);
    int matched = 0, total = 0, hooksMatched = 0, hooks = 0;
    std::vector<std::string> differ;
    for (const CheckSite& s : kCheckSites) {
        total++; if (s.hook[0]) hooks++;
        uint64_t rva = s.addr - imageBase; const uint8_t* at = nullptr;
        for (int i = 0; i < nt->FileHeader.NumberOfSections; i++)
            if (rva >= sec[i].VirtualAddress && rva + 16 <= sec[i].VirtualAddress + sec[i].SizeOfRawData && sec[i].PointerToRawData + (rva - sec[i].VirtualAddress) + 16 <= n)
                at = base + sec[i].PointerToRawData + (rva - sec[i].VirtualAddress);
        if (at && fnv1a(at, 16) == s.hash) { matched++; if (s.hook[0]) hooksMatched++; }
        else { char line[160]; sprintf_s(line, "  0x%llx%s%s", s.addr, s.hook[0] ? "  hook: " : "", s.hook); differ.push_back(line); }
    }
    out("Image base: 0x%llx (the Steam build: 0x140000000)\n", imageBase);
    out("Addresses the mod uses: %d of %d match (hook sites: %d of %d)\n", matched, total, hooksMatched, hooks);
    if (!same) {
        if (matched == total) { out("=> Not byte-identical, but every address the mod uses matches: the mod's hooks should fit this build.\n"); result = 1; }
        else {
            out("=> A DIFFERENT BUILD: the mod's addresses would have to be found again for it. Differing:\n");
            for (size_t i = 0; i < differ.size() && i < 40; i++) out("%s\n", differ[i].c_str());
            if (differ.size() > 40) out("  ... and %zu more\n", differ.size() - 40);
            result = 2;
        }
    }
    out("\n");
    UnmapViewOfFile(base); CloseHandle(m); CloseHandle(f);
    return result;
}

int wmain(int argc, wchar_t** argv) {
    wchar_t self[MAX_PATH]; GetModuleFileNameW(nullptr, self, MAX_PATH);
    std::wstring rp = self; rp = rp.substr(0, rp.find_last_of(L'\\') + 1) + L"sws_check_report.txt";
    _wfopen_s(&g_report, rp.c_str(), L"w");
    out("sws_check: does this copy of STAR WARS: Squadrons match the build the community mod is made for? (read-only)\n");
    out("Checks %zu game addresses the mod uses, and the whole file's SHA-256. Nothing is started or changed.\n\n", sizeof kCheckSites / sizeof kCheckSites[0]);
    std::vector<Candidate> found;
    bool pause = true;
    for (int i = 1; i < argc; i++) {
        if (!wcscmp(argv[i], L"--no-pause")) { pause = false; continue; }
        std::wstring p = argv[i]; size_t before = found.size();
        if (exists(p)) found.push_back({ p, L"given on the command line" });   // the exe itself (or dragged onto this)
        else add(found, p, L"given on the command line");                     // a folder holding it
        if (found.size() == before) out("Not found: %s\n", narrow(p).c_str());
    }
    if (found.empty()) {
        from_uninstall(found, HKEY_LOCAL_MACHINE, KEY_WOW64_64KEY);
        from_uninstall(found, HKEY_LOCAL_MACHINE, KEY_WOW64_32KEY);
        from_uninstall(found, HKEY_CURRENT_USER, 0);
        from_epic(found);
        from_steam(found);
    }
    int worst = -1;
    if (found.empty()) out("Couldn't find starwarssquadrons.exe. Drag it onto sws_check.exe, or run: sws_check.exe \"<path to starwarssquadrons.exe>\"\n");
    for (auto& c : found) { int r = check(c.path, c.source); if (r > worst) worst = r; }
    out("Report saved to %s\n", narrow(rp).c_str());
    out("If you're helping with issue #17, attach that file to the issue: https://github.com/Reidmcc/sws-community/issues/17\n");
    if (g_report) fclose(g_report);
    if (pause) { printf("\nPress Enter to close.\n"); getchar(); }
    return worst < 0 ? 4 : worst;
}
