"""Generate mod/check_sites.h for sws_check.exe (issue #17): what a copy of the game must match for the mod to work on it.

Every game address the mod's source names (the DLL: hook sites, functions it calls, vtables it patches, data it reads;
the value engine's type table: ClassInfos) is read from our Steam exe (work/starwarssquadrons.exe, a byte-identical copy
of the install), and a hash of the 16 bytes there is stored: no game code goes into the repo, only hashes. sws_check.exe
hashes the same 16 bytes in another copy's exe and compares. The whole file's SHA-256 is stored too: if it matches, the
copy is the same build outright.

Usage: .venv/Scripts/python.exe -I tools/gen_check_sites.py
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pemap import PE  # noqa: E402

PROJECT = os.path.dirname(HERE)
EXE = os.path.join(PROJECT, "work", "starwarssquadrons.exe")
SOURCES = [os.path.join(PROJECT, "mod", "sws_probe.cpp"), os.path.join(PROJECT, "mod", "config_types.h")]
OUT = os.path.join(PROJECT, "mod", "check_sites.h")
ADDR = re.compile(r"\b0x(14[0-9a-fA-F]{7})(?:ull|ULL)?\b")
WINDOW = 16


def fnv1a(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def main():
    pe = PE(EXE)
    names = {}
    for src in SOURCES:
        text = open(src, encoding="utf-8").read()
        for m in ADDR.finditer(text):
            names.setdefault(int(m.group(1), 16), os.path.basename(src))
    # hook sites by name, for a readable report
    site_names = dict((int(a, 16), n) for n, a in re.findall(r'\{"([^"]+)", 0x(14[0-9a-f]{7}), \d+,', open(SOURCES[0], encoding="utf-8").read()))
    rows, skipped = [], 0
    for addr in sorted(names):
        b = pe.read(addr, WINDOW)
        if b is None or len(b) < WINDOW:   # not backed by the file (zero-filled data): nothing on disk to compare
            skipped += 1
            continue
        label = site_names.get(addr, "")
        rows.append((addr, fnv1a(b), label))
    data = open(EXE, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    L = ["// Generated by tools/gen_check_sites.py from the Steam build the mod targets. Do not edit by hand.",
         "// Each check: a game address the mod uses, and the FNV-1a hash of the 16 bytes there (no game bytes stored).",
         "#pragma once",
         f'static const char kSteamSha256[] = "{sha}";',
         f"static const unsigned long long kSteamSize = {len(data)}ull;",
         "struct CheckSite { unsigned long long addr; unsigned hash; const char* hook; };",
         "static const CheckSite kCheckSites[] = {"]
    for addr, h, label in rows:
        L.append(f'    {{ 0x{addr:x}ull, 0x{h:08x}u, "{label}" }},')
    L.append("};")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    hooks = sum(1 for r in rows if r[2])
    print(f"{len(rows)} addresses ({hooks} hook sites), {skipped} not file-backed (skipped); sha256 {sha[:16]}... -> {OUT}")


if __name__ == "__main__":
    main()
