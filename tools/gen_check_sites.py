"""Generate mod/check_sites.h for sws_check.exe (issue #17): what a copy of the game must match for the mod to work on it.

Every game address the mod's source names (the DLL: hook sites, functions it calls, vtables it patches, data it reads;
the value engine's type table: ClassInfos) is read from our Steam exe (work/starwarssquadrons.exe, a byte-identical copy
of the install), and a hash of the 16 bytes there is stored: no game code goes into the repo, only hashes. sws_check.exe
hashes the same 16 bytes in another copy's exe and compares. The whole file's SHA-256 is stored too: if it matches, the
copy is the same build outright.

For a different build, sws_check also searches the whole file for each address's code: a rolling hash of the 32 bytes
there (polynomial, base FNV's 64-bit prime, mod 2^64), so the same code at another address is found and its shift
reported. And the Steam build's sections, with their entropy, so an exe whose code is encrypted on disk (entropy near 8
bits per byte, and nothing found) can be told from one that was rebuilt.

Usage: .venv/Scripts/python.exe -I tools/gen_check_sites.py
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pemap import PE  # noqa: E402

PROJECT = os.path.dirname(HERE)
EXE = os.path.join(PROJECT, "work", "starwarssquadrons.exe")
SOURCES = [os.path.join(PROJECT, "mod", "sws_probe.cpp"), os.path.join(PROJECT, "mod", "config_types.h")]
OUT = os.path.join(PROJECT, "mod", "check_sites.h")
ADDR = re.compile(r"\b0x(14[0-9a-fA-F]{7})(?:ull|ULL)?\b")
WINDOW = 16
SEARCH = 32                      # the searched window
BASE = 0x100000001B3             # FNV-1a's 64-bit prime, as the rolling hash's base
MASK = (1 << 64) - 1


def fnv1a(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def roll(b):
    h = 0
    for x in b:
        h = (h * BASE + x) & MASK
    return h


def entropy(b):
    import math
    if not b:
        return 0.0
    counts = [0] * 256
    for x in b:
        counts[x] += 1
    n = len(b)
    return -sum(c / n * math.log2(c / n) for c in counts if c)


def entropy_fast(m, off, size):
    # the byte histogram in chunks (bytes.count per value is fast enough for a few hundred MB)
    import math
    counts = [0] * 256
    step = 1 << 24
    for o in range(off, off + size, step):
        chunk = m[o:min(o + step, off + size)]
        for v in range(256):
            counts[v] += chunk.count(bytes([v]))
    n = size
    return -sum(c / n * math.log2(c / n) for c in counts if c) if n else 0.0


def main():
    pe = PE(EXE)
    names = {}
    for src in SOURCES:
        text = open(src, encoding="utf-8").read()
        for m in ADDR.finditer(text):
            names.setdefault(int(m.group(1), 16), os.path.basename(src))
    # hook sites by name, for a readable report
    site_names = dict((int(a, 16), n) for n, a in re.findall(r'\{"([^"]+)", 0x(14[0-9a-f]{7}), \d+,', open(SOURCES[0], encoding="utf-8").read()))
    rows, skipped = [], 0
    for addr in sorted(names):
        b = pe.read(addr, WINDOW)
        if b is None or len(b) < WINDOW:   # not backed by the file (zero-filled data): nothing on disk to compare
            skipped += 1
            continue
        label = site_names.get(addr, "")
        s = pe.read(addr, SEARCH)
        rows.append((addr, fnv1a(b), roll(s) if s is not None and len(s) == SEARCH else 0, label))
    data = open(EXE, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    L = ["// Generated by tools/gen_check_sites.py from the Steam build the mod targets. Do not edit by hand.",
         "// Each check: a game address the mod uses, and the FNV-1a hash of the 16 bytes there (no game bytes stored).",
         "#pragma once",
         f'static const char kSteamSha256[] = "{sha}";',
         f"static const unsigned long long kSteamSize = {len(data)}ull;",
         f"static const unsigned kSearchWindow = {SEARCH};   // the rolling hash's window (base 0x{BASE:x}, mod 2^64)",
         "struct CheckSite { unsigned long long addr; unsigned hash; unsigned long long roll; const char* hook; };",
         "static const CheckSite kCheckSites[] = {"]
    for addr, h, r, label in rows:
        L.append(f'    {{ 0x{addr:x}ull, 0x{h:08x}u, 0x{r:016x}ull, "{label}" }},')
    L.append("};")
    L.append("// the Steam build's sections: name, virtual address, raw size, entropy of the raw bytes (bits per byte)")
    L.append("struct SteamSection { const char* name; unsigned va, raw; double entropy; };")
    L.append("static const SteamSection kSteamSections[] = {")
    for name, va, vsz, rptr, rsz in pe.sections:
        L.append(f'    {{ "{name}", 0x{va:x}u, 0x{rsz:x}u, {entropy_fast(pe.m, rptr, rsz):.3f} }},')
    L.append("};")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    hooks = sum(1 for r in rows if r[3])
    print(f"{len(rows)} addresses ({hooks} hook sites), {skipped} not file-backed (skipped); sha256 {sha[:16]}... -> {OUT}")


if __name__ == "__main__":
    main()
