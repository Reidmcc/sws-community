"""Generate mod/app/Words.cs: readable names for the settings app ("afterburnerchargerate" -> "afterburner charge rate").

The value keys are lowercase, so their word boundaries are gone; the game's runtime type info (notes/sws_runtime_types.json,
decoded from the exe by our own tools) has every field in its original CamelCase. Two tables:
  - Exact: each field name of the types the value engine walks (mod/config_types.h), lowercased -> its words.
  - Vocabulary: every word in every type and field name, for names that only exist at runtime (the attributes a
    component modifies, like targetingenemylockmultiplier); the app splits those into the fewest known words.

Usage: .venv/Scripts/python.exe -I tools/gen_app_words.py
"""
import collections
import json
import os
import re

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPES = os.path.join(PROJECT, "notes", "sws_runtime_types.json")
CONFIG_TYPES = os.path.join(PROJECT, "mod", "config_types.h")
OUT = os.path.join(PROJECT, "mod", "app", "Words.cs")
SPLIT = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+")


def words(name):
    return [w.lower() for w in SPLIT.findall(name)]


def main():
    recs = json.load(open(TYPES, encoding="utf-8"))
    walked = set(re.findall(r'\{"([A-Za-z0-9_]+)", 0x[0-9a-f]+ull', open(CONFIG_TYPES, encoding="utf-8").read()))
    walked |= {"StarshipCustomConfig", "StarshipBaseConfig"}
    exact, vocab = {}, set()
    # an acronym is a word the game writes in capitals more often than capitalized (AI, UI yes; MAX, ALL no)
    caps, normal = collections.Counter(), collections.Counter()
    for t in recs:
        for n in [t["name"]] + [f["name"] for f in t.get("fields") or []]:
            for w in SPLIT.findall(n):
                if w.isalpha() and len(w) > 1:
                    (caps if w.isupper() else normal)[w.lower()] += 1
    acronyms = {w for w in caps if len(w) <= 4 and caps[w] > normal[w]}

    def label(w):
        return w.upper() if w.lower() in acronyms else w[:1].upper() + w[1:].lower()

    for t in recs:
        vocab.update(words(t["name"]))
        for f in t.get("fields") or []:
            vocab.update(words(f["name"]))
            if t["name"] in walked:
                ws = SPLIT.findall(f["name"])
                if len(ws) > 1 or ws[:1] != [f["name"].lower()]:
                    exact.setdefault(f["name"].lower(), " ".join(label(w) for w in ws))
    vocab = sorted(w for w in vocab if w.isalpha() and (len(w) > 1 or w in ("a", "x", "y", "z")))
    L = ["// Generated by tools/gen_app_words.py from the game's runtime type info. Do not edit by hand.",
         "// Readable names for the settings app: exact field names, and a vocabulary for splitting the rest.",
         "namespace SwsSettings", "{", "    static partial class Words", "    {",
         "        static readonly string[][] ExactPairs = {"]
    for k in sorted(exact):
        L.append(f'            new[] {{ "{k}", "{exact[k]}" }},')
    L += ["        };", "        // words the game writes in capitals (AI, UI...), kept that way in split names",
          "        static readonly string[] Acronyms = { " + " ".join(f'"{a}",' for a in sorted(acronyms)) + " };",
          "        static readonly string[] Vocabulary = {"]
    for i in range(0, len(vocab), 12):
        L.append("            " + " ".join(f'"{w}",' for w in vocab[i:i + 12]))
    L += ["        };", "    }", "}"]
    open(OUT, "w", encoding="utf-8", newline="\r\n").write("\n".join(L) + "\n")
    print(f"{len(exact)} exact names, {len(vocab)} words -> {OUT}")


if __name__ == "__main__":
    main()
