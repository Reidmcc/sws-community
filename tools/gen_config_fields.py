"""Generate mod/config_fields.h: the fields the runtime value engine (issue #3) can change.

Input: notes/sws_runtime_types.json (the game's runtime type info, decoded from the exe by our own tools) and the
exe copy in work/ (to find each type's runtime ClassInfo, the object whose first field points at the type's
description). Output: a C table of {class, field name (lowercase), offset, kind} for the supported field kinds:
  0 = Float32                     written in place
  1 = IncomAttributeFloat (ptr)   written at the attribute object's Value (+32) and in the config's
                                  FloatIncomAttributesToRegister entry with the same attribute id
  2 = Float32-Array               written per element, key "field[i]"

Usage: .venv/Scripts/python.exe -I tools/gen_config_fields.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pemap import PE  # noqa: E402

PROJECT = os.path.dirname(HERE)
TYPES = os.path.join(PROJECT, "notes", "sws_runtime_types.json")
EXE = os.path.join(PROJECT, "work", "starwarssquadrons.exe")
OUT = os.path.join(PROJECT, "mod", "config_fields.h")

CLASSES = ["StarshipMovementConfig", "StarshipShieldData", "StarshipHealthDamageData", "IncomBulletConfig"]
KINDS = {"Float32": 0, "IncomAttributeFloat": 1, "Float32-Array": 2}


def class_info(pe, data, typedata_va):
    """The runtime ClassInfo: the one .rdata object whose first qword is the type description's address."""
    needle = typedata_va.to_bytes(8, "little")
    hits = []
    i = data.find(needle)
    while i != -1:
        for name, sva, vsz, rptr, rsz in pe.sections:
            if rptr <= i < rptr + rsz:
                hits.append((pe.base + sva + i - rptr, name))
        i = data.find(needle, i + 1)
    rdata = [va for va, name in hits if name == ".rdata"]
    if len(rdata) != 1:
        raise SystemExit(f"expected one ClassInfo for {typedata_va:#x}, found {hits}")
    return rdata[0]


def main():
    recs = json.load(open(TYPES, encoding="utf-8"))
    by = {r["name"]: r for r in recs if isinstance(r, dict) and "name" in r}
    pe = PE(EXE)
    data = bytes(pe.m)
    lines = [
        "// Generated by tools/gen_config_fields.py from the game's runtime type info. Do not edit by hand.",
        "// kind: 0 = Float32, 1 = IncomAttributeFloat pointer (Value at +32, plus its attribute-list entry),",
        "//       2 = Float32-Array (pointer; element count at -4)",
        "#pragma once",
        "struct ConfigClass { const char* name; uint64_t classInfo; };",
        "struct ConfigField { int cls; const char* name; uint32_t offset; int kind; };",
        "static const ConfigClass kConfigClasses[] = {",
    ]
    fields = []
    for ci, cname in enumerate(CLASSES):
        rec = by[cname]
        info = class_info(pe, data, int(rec["va"], 16))
        lines.append(f'    {{"{cname}", 0x{info:x}ull}},')
        for f in sorted(rec["fields"], key=lambda f: f["offset"]):
            if f["type"] in KINDS:
                fields.append(f'    {{{ci}, "{f["name"].lower()}", 0x{f["offset"]:x}, {KINDS[f["type"]]}}},   // {cname}.{f["name"]}')
    lines.append("};")
    lines.append("static const ConfigField kConfigFields[] = {")
    lines.extend(fields)
    lines.append("};")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(CLASSES)} classes, {len(fields)} fields -> {OUT}")


if __name__ == "__main__":
    main()
