"""Generate mod/app/Tips.cs: each value's hover tip and, where the generated name reads badly, a better display name.

The source is tools/value_tips.tsv (tab-separated, UTF-8, a header row), one row per value the settings app exposes:
  key       <type>.<field path without indices>, as limits.ini names it but with the pools folded together:
            starshipweaponconfig (primary and aux alike), the capital-ship pools under their base type, and the three
            component types as "components"
  name      a display name for the field's last part, or blank to keep the one tools/gen_app_words.py gives it
  tip       one or two sentences on what the value does in play ("Effect not known." where nobody could tell)
  evidence  how the tip is known: name (the name and stock values only), data, notes, code, flown, unknown;
            optionally ": <detail>"

Usage: .venv/Scripts/python.exe -I tools/gen_app_tips.py
"""
import csv
import os

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(PROJECT, "tools", "value_tips.tsv")
OUT = os.path.join(PROJECT, "mod", "app", "Tips.cs")
KINDS = {"name", "data", "notes", "code", "flown", "unknown"}


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = list(csv.DictReader(open(SRC, encoding="utf-8", newline=""), delimiter="\t"))
    seen = set()
    for r in rows:
        k = r["key"].strip()
        if not k or k in seen:
            raise SystemExit(f"value_tips.tsv: empty or repeated key {k!r}")
        seen.add(k)
        kind = r["evidence"].split(":")[0].strip()
        if kind not in KINDS:
            raise SystemExit(f"value_tips.tsv: {k}: evidence {r['evidence']!r} isn't one of {sorted(KINDS)}")
        if not r["tip"].strip():
            raise SystemExit(f"value_tips.tsv: {k}: no tip")
    out = ["// Generated by tools/gen_app_tips.py from tools/value_tips.tsv. Do not edit by hand.",
           "// Each value's hover tip, how it is known, and a better display name where the generated one reads badly.",
           "namespace SwsSettings", "{", "    static partial class Tips", "    {",
           "        // key, display name (\"\" keeps the generated one), tip, evidence kind",
           "        static readonly string[][] Rows = {"]
    for r in sorted(rows, key=lambda r: r["key"]):
        kind = r["evidence"].split(":")[0].strip()
        out.append("            new[] { " + ", ".join(cs(x) for x in (r["key"].strip(), r["name"].strip(), r["tip"].strip(), kind)) + " },")
    out += ["        };", "    }", "}", ""]
    open(OUT, "w", encoding="utf-8", newline="\r\n").write("\n".join(out))
    print(f"{len(rows)} tips -> {OUT}")


if __name__ == "__main__":
    main()
